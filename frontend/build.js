// Builds the static frontend into ./dist and writes the backend URL into js/config.js.
// BACKEND_URL comes from Vercel's Environment Variables, or from frontend/.env when building locally.
// Usage:  node build.js
const fs = require("fs");
const path = require("path");

const root = __dirname;
const dist = path.join(root, "dist");

function readDotEnv(file) {
  const vars = {};
  if (!fs.existsSync(file)) return vars;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/i);
    if (m && !line.trim().startsWith("#")) vars[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
  return vars;
}

const env = { ...readDotEnv(path.join(root, ".env")), ...process.env };
let backend = (env.BACKEND_URL || "").trim().replace(/\/+$/, "");

if (backend && !/^https?:\/\/[^\s/]+/i.test(backend)) {
  console.error(`BACKEND_URL must start with http:// or https:// (got "${backend}")`);
  process.exit(1);
}
if (backend.endsWith("/api")) backend = backend.slice(0, -4); // the app adds /api itself

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
for (const item of ["index.html", "css", "js"]) {
  fs.cpSync(path.join(root, item), path.join(dist, item), { recursive: true });
}
fs.writeFileSync(
  path.join(dist, "js", "config.js"),
  `// Generated by build.js – do not edit.\nwindow.APP_CONFIG = {\n  API_BASE: ${JSON.stringify(backend)},\n};\n`
);

console.log(backend ? `Frontend built. Backend URL: ${backend}` : "Frontend built. BACKEND_URL not set – using same origin.");
